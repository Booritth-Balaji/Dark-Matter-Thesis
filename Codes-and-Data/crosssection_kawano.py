import numpy as np

def crosssection(T, reaction):
    """
    Returns the forward thermally averaged cross section  N_A * <σv>
    (in cm³ mol⁻¹ s⁻¹) for a specified BBN reaction at temperature T (MeV).

    Uses the analytic Kawano (1992) fitting formulae.
    T9 = temperature in units of 10^9 K; the conversion from MeV is done
    internally via MeVtoK9().

    Parameters
    ----------
    T        : float or array-like
               Temperature in MeV.
    reaction : str or int
               Reaction name (string) matching the notebook convention, e.g.
               "p+n->D+gamma", or the reaction index (int, 1–11).

    Returns
    -------
    float or ndarray
        N_A * <σv> in cm³ mol⁻¹ s⁻¹.

    Raises
    ------
    ValueError
        If the reaction name/index is not recognised.

    Reactions (with Kawano reaction numbers in parentheses)
    --------------------------------------------------------
     1.  p+n->D+gamma       p(n,γ)d
     2.  D+p->He3+gamma     d(p,γ)³He
     3.  D+D->He3+n         d(d,n)³He
     4.  D+D->p+T           d(d,p)t
     5.  He3+n->T+p         ³He(n,p)t
     6.  T+D->n+He4         t(d,n)⁴He
     7.  He3+D->p+He4       ³He(d,p)⁴He
     8.  He3+He4->gamma+Be7 ³He(α,γ)⁷Be
     9.  T+He4->gamma+Li7   t(α,γ)⁷Li
    10.  Be7+n->p+Li7       ⁷Be(n,p)⁷Li
    11.  Li7+p->He4+He4     ⁷Li(p,α)⁴He
    """

    T9 = MeVtoK9(T)   # convert input temperature MeV -> T9

    # Kawano fits are only valid for 0.001 ≤ T9 ≤ 15; clip to avoid blow-up
    T9 = np.clip(T9, 1e-3, 15.0)

    # ------------------------------------------------------------------
    # Reaction 1 : p(n,γ)d
    # σ = 4.742 × 10⁴ (1 − 0.850 T9^(1/2) + 0.490 T9 − 0.0962 T9^(3/2)
    #                   + 8.47 × 10⁻³ T9² − 2.80 × 10⁻⁴ T9^(5/2))
    # ------------------------------------------------------------------
    if reaction in ("p+n->D+gamma", 1):
        sigma = (4.742e4
                 * (1.0
                    - 0.850   * T9**(1/2)
                    + 0.490   * T9
                    - 0.0962  * T9**(3/2)
                    + 8.47e-3 * T9**2
                    - 2.80e-4 * T9**(5/2)))

    # ------------------------------------------------------------------
    # Reaction 2 : d(p,γ)³He
    # σ = 2.65 × 10³ T9^(−2/3) exp(−3.720/T9^(1/3))
    #       × (1 + 0.112 T9^(1/3) + 1.99 T9^(2/3) + 1.56 T9
    #            + 0.162 T9^(4/3) + 0.324 T9^(5/3))
    # ------------------------------------------------------------------
    elif reaction in ("D+p->He3+gamma", 2):
        sigma = (2.65e3
                 * T9**(-2/3)
                 * np.exp(-3.720 / T9**(1/3))
                 * (1.0
                    + 0.112  * T9**(1/3)
                    + 1.99   * T9**(2/3)
                    + 1.56   * T9
                    + 0.162  * T9**(4/3)
                    + 0.324  * T9**(5/3)))

    # ------------------------------------------------------------------
    # Reaction 3 : d(d,n)³He
    # σ = 3.95 × 10⁸ T9^(−2/3) exp(−4.259/T9^(1/3))
    #       × (1 + 0.098 T9^(1/3) + 0.765 T9^(4/3) + 0.525 T9
    #            + 9.61 × 10⁻³ T9^(4/3) + 0.0167 T9^(5/3))
    # ------------------------------------------------------------------
    elif reaction in ("D+D->He3+n", 3):
        sigma = (3.95e8
                 * T9**(-2/3)
                 * np.exp(-4.259 / T9**(1/3))
                 * (1.0
                    + 0.098   * T9**(1/3)
                    + 0.765   * T9**(2/3)
                    + 0.525   * T9
                    + 9.61e-3 * T9**(4/3)
                    + 0.0167  * T9**(5/3)))

    # ------------------------------------------------------------------
    # Reaction 4 : d(d,p)t
    # σ = 4.17 × 10⁸ T9^(−2/3) exp(−4.258/T9^(1/3))
    #       × (1 + 0.098 T9^(1/3) + 0.518 T9^(2/3) + 0.355 T9
    #            − 0.010 T9^(4/3) − 0.018 T9^(5/3))
    # ------------------------------------------------------------------
    elif reaction in ("D+D->p+T", 4):
        sigma = (4.17e8
                 * T9**(-2/3)
                 * np.exp(-4.258 / T9**(1/3))
                 * (1.0
                    + 0.098  * T9**(1/3)
                    + 0.518  * T9**(2/3)
                    + 0.355  * T9
                    - 0.010  * T9**(4/3)
                    - 0.018  * T9**(5/3)))

    # ------------------------------------------------------------------
    # Reaction 5 : ³He(n,p)t
    # σ = 7.21 × 10⁸ (1 − 0.508 T9² + 0.228 T9)
    # ------------------------------------------------------------------
    elif reaction in ("He3+n->T+p", 5):
        sigma = 7.21e8 * (1.0 - 0.508 * T9**(1/2) + 0.228 * T9)

    # ------------------------------------------------------------------
    # Reaction 6 : t(d,n)⁴He
    # σ = 1.063 × 10¹¹ T9^(−2/3) exp[−4.559/T9^(1/3) − (T9/0.0754)²]
    #       × (1 + 0.092 T9^(1/3) − 0.375 T9^(2/3) − 0.242 T9
    #            + 33.82 T9^(4/3) + 55.42 T9^(5/3))
    #     + 8.047 × 10⁸ T9^(−2/3) exp(−0.4857/T9)
    # ------------------------------------------------------------------
    elif reaction in ("T+D->n+He4", 6):
        sigma = (1.063e11
                 * T9**(-2/3)
                 * np.exp(-4.559 / T9**(1/3) - (T9 / 0.0754)**2)
                 * (1.0
                    + 0.092  * T9**(1/3)
                    - 0.375  * T9**(2/3)
                    - 0.242  * T9
                    + 33.82  * T9**(4/3)
                    + 55.42  * T9**(5/3))
                 + 8.047e8 * T9**(-2/3) * np.exp(-0.4857 / T9))

    # ------------------------------------------------------------------
    # Reaction 7 : ³He(d,p)⁴He
    # σ = 5.021 × 10¹⁰ T9^(−2/3) exp[−7.144/T9^(1/3) − (T9/0.270)²]
    #       × (1 + 0.058 T9^(1/3) + 0.603 T9^(2/3) + 0.245 T9
    #            + 6.97 T9^(4/3) + 7.19 T9^(5/3))
    #     + 5.212 × 10⁸ T9^(−1/2) exp(−1.762/T9)
    # ------------------------------------------------------------------
    elif reaction in ("He3+D->p+He4", 7):
        sigma = (5.021e10
                 * T9**(-2/3)
                 * np.exp(-7.144 / T9**(1/3) - (T9 / 0.270)**2)
                 * (1.0
                    + 0.058  * T9**(1/3)
                    + 0.603  * T9**(2/3)
                    + 0.245  * T9
                    + 6.97   * T9**(4/3)
                    + 7.19   * T9**(5/3))
                 + 5.212e8 * T9**(-1/2) * np.exp(-1.762 / T9))

    # ------------------------------------------------------------------
    # Reaction 8 : ³He(α,γ)⁷Be
    # T9a = T9 / (1 + 0.1071 T9)
    # σ = 4.817 × 10⁶ T9^(−2/3) exp(−14.964/T9^(1/3))
    #       × (1 + 0.0325 T9^(1/3) − 1.04 × 10⁻³ T9^(2/3) − 2.37 × 10⁻⁴ T9
    #            − 8.11 × 10⁻⁵ T9^(4/3) − 4.69 × 10⁻⁵ T9^(5/3))
    #     + 5.938 × 10⁶ T9a^(5/6) T9^(−3/2) exp(−12.859/T9a^(1/3))
    # ------------------------------------------------------------------
    elif reaction in ("He3+He4->gamma+Be7", 8):
        T9a = T9 / (1.0 + 0.1071 * T9)
        sigma = (4.817e6
                 * T9**(-2/3)
                 * np.exp(-14.964 / T9**(1/3))
                 * (1.0
                    + 0.0325  * T9**(1/3)
                    - 1.04e-3 * T9**(2/3)
                    - 2.37e-4 * T9
                    - 8.11e-5 * T9**(4/3)
                    - 4.69e-5 * T9**(5/3))
                 + 5.938e6 * T9a**(5/6) * T9**(-3/2) * np.exp(-12.859 / T9a**(1/3)))

    # ------------------------------------------------------------------
    # Reaction 9 : t(α,γ)⁷Li
    # T9a = T9 / (1 + 0.1378 T9)
    # σ = 3.032 × 10⁵ T9^(−2/3) exp(−8.090/T9^(1/3))
    #       × (1 + 0.0516 T9^(1/3) + 0.0229 T9^(2/3) + 8.28 × 10⁻³ T9
    #            − 3.28 × 10⁻⁴ T9^(4/3) − 3.01 × 10⁻⁴ T9^(5/3))
    #     + 5.109 × 10⁵ T9a^(5/6) T9^(−3/2) exp(−8.068/T9a^(1/3))
    # ------------------------------------------------------------------
    elif reaction in ("T+He4->gamma+Li7", 9):
        T9a = T9 / (1.0 + 0.1378 * T9)
        sigma = (3.032e5
                 * T9**(-2/3)
                 * np.exp(-8.090 / T9**(1/3))
                 * (1.0
                    + 0.0516  * T9**(1/3)
                    + 0.0229  * T9**(2/3)
                    + 8.28e-3 * T9
                    - 3.28e-4 * T9**(4/3)
                    - 3.01e-4 * T9**(5/3))
                 + 5.109e5 * T9a**(5/6) * T9**(-3/2) * np.exp(-8.068 / T9a**(1/3)))

    # ------------------------------------------------------------------
    # Reaction 10 : ⁷Be(n,p)⁷Li
    # T9a = T9 / (1 + 13.076 T9)
    # σ = 2.675 × 10⁹ (1 − 0.560 T9 + 0.179 T9 − 0.0283 T9^(3/2)
    #                   + 2.21 × 10⁻³ T9² − 6.85 × 10⁻⁵ T9^(5/2))
    #     + 9.391 × 10⁸ (T9a/T9)^(3/2)
    #     + 4.467 × 10⁷ T9^(−3/2) exp(−0.07486/T9)
    #
    # NOTE: The image shows two consecutive "+0.179 T9" looking terms inside
    # the polynomial bracket.  One is likely "+0.179 T9^(1/2)" (a square-root
    # term) which is the standard form from Kawano (1992) Table IV.
    # The formula below matches the image literally; adjust if needed.
    # ------------------------------------------------------------------
    elif reaction in ("Be7+n->p+Li7", 10):
        T9a = T9 / (1.0 + 13.076 * T9)
        sigma = (2.675e9
                 * (1.0
                    - 0.560   * T9**(1/2)
                    + 0.179   * T9         # ← see note above; image ambiguous
                    - 0.0283  * T9**(3/2)
                    + 2.21e-3 * T9**2
                    - 6.85e-5 * T9**(5/2))
                 + 9.391e8 * (T9a / T9)**(3/2)
                 + 4.467e7 * T9**(-3/2) * np.exp(-0.07486 / T9))

    # ------------------------------------------------------------------
    # Reaction 11 : ⁷Li(p,α)⁴He
    # T9a = T9 / (1 + 0.759 T9)
    # σ = 1.096 × 10⁹ T9^(−2/3) exp(−8.472/T9^(1/3))
    #     − 4.830 × 10⁸ T9a^(5/6) T9^(−3/2) exp(−8.472/T9a^(1/3))
    #     + 1.06 × 10¹⁰ T9^(−3/2) exp(−30.442/T9)
    #     + 1.56 × 10⁵ T9^(−2/3) exp[−8.472/T9^(1/3) − (T9/1.696)²]
    #         × (1 + 0.049 T9^(1/3) − 2.498 T9^(2/3) + 0.860 T9
    #              + 3.518 T9^(4/3) + 3.08 T9^(5/3))
    #     + 1.55 × 10⁶ T9^(−3/2) exp(−4.478/T9)
    # ------------------------------------------------------------------
    elif reaction in ("Li7+p->He4+He4", 11):
        T9a = T9 / (1.0 + 0.759 * T9)
        sigma = (1.096e9
                 * T9**(-2/3)
                 * np.exp(-8.472 / T9**(1/3))
                 - 4.830e8
                 * T9a**(5/6)
                 * T9**(-3/2)
                 * np.exp(-8.472 / T9a**(1/3))
                 + 1.06e10 * T9**(-3/2) * np.exp(-30.442 / T9)
                 + 1.56e5
                 * T9**(-2/3)
                 * np.exp(-8.472 / T9**(1/3) - (T9 / 1.696)**2)
                 * (1.0
                    + 0.049  * T9**(1/3)
                    - 2.498  * T9**(2/3)
                    + 0.860  * T9
                    + 3.518  * T9**(4/3)
                    + 3.08   * T9**(5/3))
                 + 1.55e6 * T9**(-3/2) * np.exp(-4.478 / T9))

    else:
        raise ValueError(
            f"Reaction '{reaction}' not recognised. "
            "Accepted names: "
            "'p+n->D+gamma', 'D+p->He3+gamma', 'D+D->He3+n', 'D+D->p+T', "
            "'He3+n->T+p', 'T+D->n+He4', 'He3+D->p+He4', "
            "'He3+He4->gamma+Be7', 'T+He4->gamma+Li7', "
            "'Be7+n->p+Li7', 'Li7+p->He4+He4' "
            "(or integer index 1–11)."
        )

    return sigma
